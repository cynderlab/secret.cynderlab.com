"""Tiny dependency-free i18n: Accept-Language negotiation + string catalogs.

The API and /llms.txt intentionally stay English — only the human interface
is translated. No cookies: language follows the browser, per request.
"""

SUPPORTED = ("en", "ca", "es")


def negotiate(header: str | None) -> str:
    if not header:
        return "en"
    best, best_q = "en", 0.0
    for part in header.split(","):
        pieces = part.strip().split(";")
        code = pieces[0].strip().lower()[:2]
        q = 1.0
        for p in pieces[1:]:
            p = p.strip()
            if p.startswith("q="):
                try:
                    q = float(p[2:])
                except ValueError:
                    q = 0.0
        if code in SUPPORTED and q > best_q:
            best, best_q = code, q
    return best


def make_t(lang: str):
    catalog = TRANSLATIONS.get(lang, {})
    fallback = TRANSLATIONS["en"]

    def t(key: str, **kwargs) -> str:
        s = catalog.get(key) or fallback[key]
        return s.format(**kwargs) if kwargs else s

    return t


